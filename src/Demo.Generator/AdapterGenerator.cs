using System.Reflection;
using System.Text;
using System.Text.Json;
using Demo.Tasks;

namespace Demo.Generator;

// One generator for all tasks. Fail before writing a partial or ambiguous adapter file.
public static class AdapterGenerator
{
    public static string Generate(IEnumerable<Type> candidates, string targetNamespace = "Demo.Elsa.Generated")
    {
        var code = new StringBuilder("// <auto-generated />\n#nullable enable\nusing Elsa.Extensions;\nusing Elsa.Workflows;\nusing Elsa.Workflows.Attributes;\nusing Elsa.Workflows.Models;\n");
        code.AppendLine($"namespace {targetNamespace};");
        var names = new HashSet<string>();
        var identities = new HashSet<string>();
        foreach (var task in candidates.Where(t => t.IsClass && !t.IsAbstract).OrderBy(t => t.FullName))
        {
            var contracts = task.GetInterfaces().Where(i => i.IsGenericType && i.GetGenericTypeDefinition() == typeof(IAppTask<,>)).ToArray();
            if (contracts.Length == 0) continue;
            if (contracts.Length != 1) throw Error(task, "implement exactly one IAppTask<TInput,TOutput> contract");
            if (!task.IsVisible || task.ContainsGenericParameters) throw Error(task, "task must be public and have no open generic parameters");
            var contract = contracts.Single();
            var types = contract.GetGenericArguments();
            var constructors = types[0].GetConstructors();
            if (constructors.Length != 1) throw Error(task, "input must have exactly one public constructor");
            var fields = constructors[0].GetParameters();
            var activity = task.Name.EndsWith("Task") ? task.Name[..^4] + "Activity" : task.Name + "Activity";
            if (!names.Add(activity)) throw Error(task, $"generated class name '{activity}' is duplicated");
            var identity = task.GetCustomAttribute<TaskIdentityAttribute>();
            if (identity != null)
            {
                if (identity.Version < 1 || !identity.Name.Contains('.')) throw Error(task, "identity needs a dotted name and positive version");
                if (!identities.Add($"{identity.Name}:{identity.Version}")) throw Error(task, "task name and version are duplicated");
                var split = identity.Name.LastIndexOf('.');
                code.AppendLine($"[Activity(Namespace = {JsonSerializer.Serialize(identity.Name[..split])}, Type = {JsonSerializer.Serialize(identity.Name[(split+1)..])}, Version = {identity.Version})]");
            }
            code.AppendLine($"public sealed class {activity} : CodeActivity\n{{");
            if (identity != null)
                code.AppendLine($"    public {activity}() {{ Version = {identity.Version}; }}");
            foreach (var field in fields)
            {
                if (field.Name is "Result" || typeof(ElsaReservedNames).GetField(field.Name!) != null)
                    throw Error(task, $"input name '{field.Name}' conflicts with an activity property");
                code.AppendLine($"    [Input] public Input<{TypeName(field.ParameterType, new NullabilityInfoContext().Create(field))}> @{field.Name} {{ get; set; }} = default!;");
            }
            code.AppendLine($"    [Output] public Output<{TypeName(types[1])}> Result {{ get; set; }} = new();");
            code.AppendLine("    protected override async ValueTask ExecuteAsync(ActivityExecutionContext context)\n    {");
            // Missing binding errors should name the field instead of causing a NullReferenceException.
            foreach (var field in fields)
                code.AppendLine($"        if (@{field.Name} is null) throw new ArgumentException(\"Missing input: {field.Name}.\");");
            code.AppendLine($"        var task = context.GetRequiredService<{TypeName(contract)}>();");
            code.AppendLine($"        var input = new {TypeName(types[0])}({string.Join(", ", fields.Select(f => $"context.Get(@{f.Name})!"))});");
            code.AppendLine("        var result = await task.ExecuteAsync(input, context.CancellationToken);\n        context.Set(Result, result);\n    }\n}");
        }
        return code.ToString();
    }

    private static InvalidOperationException Error(Type task, string message) => new($"Task '{task.FullName}': {message}.");
    private static string TypeName(Type type, NullabilityInfo? nullability = null)
    {
        if (type.IsArray) return TypeName(type.GetElementType()!, nullability?.ElementType) + "[" + new string(',', type.GetArrayRank() - 1) + "]" + (nullability?.ReadState == NullabilityState.Nullable ? "?" : "");
        if (!type.IsVisible || type.IsPointer || type.IsByRef || type.ContainsGenericParameters || type.IsByRefLike)
            throw new InvalidOperationException($"Unsupported contract type: {type}.");
        if (type.IsNested && type.IsGenericType) throw new InvalidOperationException($"Nested generic contract types are not supported: {type}.");
        var name = type.IsGenericType
            ? "global::" + type.GetGenericTypeDefinition().FullName!.Split('`')[0] + "<" + string.Join(", ", type.GetGenericArguments().Select((argument, index) => TypeName(argument, nullability?.GenericTypeArguments.ElementAtOrDefault(index)))) + ">"
            : "global::" + type.FullName!.Replace('+', '.');
        return name + (!type.IsValueType && nullability?.ReadState == NullabilityState.Nullable ? "?" : "");
    }

    // Keep the demo's contract fields away from inherited activity metadata.
    private static class ElsaReservedNames
    {
        public const string Id = "", Type = "", Version = "", Name = "", Metadata = "", CustomProperties = "", SyntheticProperties = "";
    }
}
