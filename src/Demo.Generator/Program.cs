using System.Reflection;
using System.Text;
using Demo.Tasks;

if (args.Length != 1) throw new ArgumentException("Supply the output .cs path.");
string TypeName(Type t) => t.IsGenericType
    ? "global::" + t.GetGenericTypeDefinition().FullName!.Split('`')[0] + "<" + string.Join(", ", t.GetGenericArguments().Select(TypeName)) + ">"
    : "global::" + t.FullName!;
var code = new StringBuilder("// <auto-generated />\n#nullable enable\nusing Elsa.Extensions;\nusing Elsa.Workflows;\nusing Elsa.Workflows.Attributes;\nusing Elsa.Workflows.Models;\nnamespace Demo.Elsa.Generated;\n");
foreach (var task in typeof(IAppTask<,>).Assembly.GetTypes().Where(t => t.IsClass && !t.IsAbstract).OrderBy(t => t.Name))
{
    var contract = task.GetInterfaces().SingleOrDefault(i => i.IsGenericType && i.GetGenericTypeDefinition() == typeof(IAppTask<,>));
    if (contract == null) continue;
    var types = contract.GetGenericArguments();
    var ctor = types[0].GetConstructors().OrderByDescending(c => c.GetParameters().Length).First();
    var fields = ctor.GetParameters();
    var activity = task.Name.Replace("Task", "Activity");
    code.AppendLine($"public sealed class {activity} : CodeActivity");
    code.AppendLine("{");
    foreach (var field in fields)
        code.AppendLine($"    [Input] public Input<{TypeName(field.ParameterType)}> {field.Name} {{ get; set; }} = default!;");
    code.AppendLine($"    [Output] public Output<{TypeName(types[1])}> Result {{ get; set; }} = new();");
    code.AppendLine("    protected override async ValueTask ExecuteAsync(ActivityExecutionContext context)");
    code.AppendLine("    {");
    code.AppendLine($"        var task = context.GetRequiredService<{TypeName(contract)}>();");
    code.AppendLine($"        var input = new {TypeName(types[0])}({string.Join(", ", fields.Select(f => $"context.Get({f.Name})!"))});");
    code.AppendLine("        var result = await task.ExecuteAsync(input, context.CancellationToken);");
    code.AppendLine("        context.Set(Result, result);");
    code.AppendLine("    }\n}");
    Console.WriteLine($"Generated {activity}: {string.Join(", ", fields.Select(f => f.Name))} → {types[1].Name}");
}
Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(args[0]))!);
File.WriteAllText(args[0], code.ToString());
